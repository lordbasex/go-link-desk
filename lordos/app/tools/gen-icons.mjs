// Rasterizes go-link's Lucide and Fyne icons into alpha masks (rsvg-convert, then ui/icons.gen.js),
// because LordOS's engine draws no SVG. Run from lordos/app: node tools/gen-icons.mjs
import fs from 'node:fs'; import os from 'node:os'; import path from 'node:path'; import zlib from 'node:zlib';
import { execFileSync } from 'node:child_process';
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'glicons'));
function decode(file) {           // RGBA8, not interlaced: what rsvg-convert writes
  const b = fs.readFileSync(file); let p = 8, w, h; const idat = [];
  while (p < b.length) { const n = b.readUInt32BE(p), t = b.toString('latin1', p + 4, p + 8), d = b.subarray(p + 8, p + 8 + n);
    if (t === 'IHDR') { w = d.readUInt32BE(0); h = d.readUInt32BE(4); if (d[8] !== 8 || d[9] !== 6) throw new Error('RGBA8 only'); }
    if (t === 'IDAT') idat.push(d); p += n + 12; }
  const raw = zlib.inflateSync(Buffer.concat(idat)), s = w * 4, px = Buffer.alloc(s * h);
  for (let y = 0; y < h; y++) { const f = raw[y * (s + 1)], o = y * (s + 1) + 1;
    for (let x = 0; x < s; x++) { const a = x >= 4 ? px[y * s + x - 4] : 0, up = y ? px[(y - 1) * s + x] : 0, c = x >= 4 && y ? px[(y - 1) * s + x - 4] : 0;
      const pa = Math.abs(up - c), pb = Math.abs(a - c), pc = Math.abs(a + up - 2 * c);
      const pr = pa <= pb && pa <= pc ? a : pb <= pc ? up : c;
      px[y * s + x] = (raw[o + x] + [0, a, up, (a + up) >> 1, pr][f]) & 255; } }
  return { w, h, px };
}
const rle = (a) => { let s = '', i = 0; while (i < a.length) { let n = 1; while (i + n < a.length && a[i + n] === a[i]) n++; s += String.fromCharCode(97 + a[i]) + (n > 1 ? n : ''); i += n; } return s; };
const SIZES = [10, 11, 13, 14, 15, 20, 22, 34];
const out = {};
function add(name, svg) {
  out[name] = {};
  for (const s of SIZES) {
    const f = path.join(tmp, `${name}.svg`), png = path.join(tmp, `${name}-${s}.png`);
    fs.writeFileSync(f, svg);
    execFileSync('rsvg-convert', ['-w', s, '-h', s, '-o', png, f]);
    const { px } = decode(png), a = new Uint8Array(s * s);
    for (let i = 0; i < a.length; i++) a[i] = Math.round(px[i * 4 + 3] / 17);
    out[name][s] = rle(a);
  }
}
for (const f of fs.readdirSync('assets/icons').filter((n) => n.endsWith('.svg'))) {
  const n = f.slice(0, -4);
  const svg = fs.readFileSync(`assets/icons/${f}`, 'utf8').replaceAll('currentColor', '#fff').replaceAll('stroke-width="2"', 'stroke-width="1.75"');
  add(n, svg);
  if (n === 'star' || n === 'house') add(n + '-fill', svg.replaceAll('fill="none"', 'fill="#fff"'));
}
for (const f of fs.readdirSync('assets/fyne').filter((n) => n.endsWith('.svg')))
  add('fyne-' + f.slice(0, -4), fs.readFileSync(`assets/fyne/${f}`, 'utf8').replace(/fill="#[0-9a-fA-F]+"/g, 'fill="#fff"').replace('<svg ', '<svg fill="#fff" '));
let body = `// Generated by tools/gen-icons.mjs from go-link's icons (Lucide, ISC; Fyne, BSD-3). Do not edit.\nexport const SIZES = ${JSON.stringify(SIZES)};\nexport const ICONS = ${JSON.stringify(out)};\n`;
const logo = decode('assets/app-96.png');
body += `export const LOGO = { width: ${logo.w}, height: ${logo.h}, b64: '${logo.px.toString('base64')}' };\n`;
fs.writeFileSync('ui/icons.gen.js', body);
console.log('icons', Object.keys(out).length, 'bytes', body.length);
