// Command gen writes keymap_gen.go from protocol/keycodes.json, the
// keyboard table the website shares (go generate in pkg/keymap).
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
)

type key struct {
	Code string `json:"code"`
	Mac  int    `json:"mac"`
	Win  int    `json:"win"`
	X11  int    `json:"x11"`
}

func main() {
	raw, err := os.ReadFile("../../../protocol/keycodes.json")
	if err != nil {
		log.Fatal(err)
	}
	var table struct {
		Keys []key `json:"keys"`
	}
	if err := json.Unmarshal(raw, &table); err != nil {
		log.Fatal(err)
	}
	var b bytes.Buffer
	b.WriteString("// Copyright (c) 2026 Federico Pereira <lord.basex@gmail.com>\n\n")
	b.WriteString("// Code generated by gen from protocol/keycodes.json; DO NOT EDIT.\n\n")
	b.WriteString("package keymap\n\n")
	b.WriteString("// Keys is the keyboard table: a key's index is its keycode on the wire.\n")
	b.WriteString("var Keys = [...]Key{\n")
	for _, k := range table.Keys {
		fmt.Fprintf(&b, "\t{Code: %q, Mac: %d, Win: %d, X11: %d},\n", k.Code, k.Mac, k.Win, k.X11)
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("keymap_gen.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}
