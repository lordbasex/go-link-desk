// Writes src/keycodes.gen.ts, the iOS app's KeyCodes.gen.swift and the
// Android app's KeyCodes.gen.kt from
// protocol/keycodes.json, the keyboard table the host shares
// (npm run gen:keycodes).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const table = JSON.parse(readFileSync(join(here, "../../../../protocol/keycodes.json"), "utf8"));
const codes = table.keys.map((k) => `  ${JSON.stringify(k.code)},`).join("\n");
writeFileSync(
  join(here, "../src/keycodes.gen.ts"),
  `// Copyright (c) 2026 Federico Pereira <lord.basex@gmail.com>
// Code generated by scripts/gen-keycodes.mjs from protocol/keycodes.json; DO NOT EDIT.

/** The keyboard table: a KeyboardEvent.code's index is its keycode on the wire. */
export const KEY_CODES: readonly string[] = [
${codes}
];
`,
);

const swift = table.keys.map((k) => `        ${JSON.stringify(k.code)},`).join("\n");
writeFileSync(
  join(here, "../../../../mobile/ios/DeskCore/Sources/DeskCore/KeyCodes.gen.swift"),
  `// Copyright (c) 2026 Federico Pereira <lord.basex@gmail.com>
// Code generated by frontend/packages/shared/scripts/gen-keycodes.mjs from protocol/keycodes.json; DO NOT EDIT.

public enum KeyCodes {
    /** The keyboard table: a KeyboardEvent.code's index is its keycode on the wire. */
    public static let codes: [String] = [
${swift}
    ]
}
`,
);

const kotlin = table.keys.map((k) => `        ${JSON.stringify(k.code)},`).join("\n");
writeFileSync(
  join(here, "../../../../mobile/android/core/src/main/kotlin/org/golink/desk/core/KeyCodes.gen.kt"),
  `// Copyright (c) 2026 Federico Pereira <lord.basex@gmail.com>
// Code generated by frontend/packages/shared/scripts/gen-keycodes.mjs from protocol/keycodes.json; DO NOT EDIT.
package org.golink.desk.core

object KeyCodes {
    /** The keyboard table: a KeyboardEvent.code's index is its keycode on the wire. */
    val codes: List<String> = listOf(
${kotlin}
    )
}
`,
);
