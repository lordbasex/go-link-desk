"""Writes the Americas map of desk.go-link.org/network (the relays' map).

The countries' outlines are Natural Earth's 1:50m (public domain), as the
world-atlas package publishes them in TopoJSON (ISC). They are projected
(Mercator) and simplified to SVG paths in
frontend/apps/web/src/network/americas.gen.ts; nothing is downloaded when
the site is built or opened.

    python3 scripts/relay-map.py
"""
import json
import math
import os
import urllib.request

SOURCE = "https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/countries-50m.json"
OUT = os.path.join(os.path.dirname(__file__), "..", "frontend", "apps", "web", "src", "network", "americas.gen.ts")
LON0, LON1, LAT0, LAT1 = -128.0, -30.0, -56.0, 58.0
WIDTH = 300
MIN_STEP = 0.9  # drop points closer than this (map units) to the last one


def merc(lat):
    return math.log(math.tan(math.pi / 4 + math.radians(lat) / 2))


def main():
    with urllib.request.urlopen(SOURCE) as r:
        topo = json.load(r)
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]
    arcs = []
    for arc in topo["arcs"]:
        x = y = 0
        pts = []
        for dx, dy in arc:
            x += dx
            y += dy
            pts.append((x * sx + tx, y * sy + ty))
        arcs.append(pts)

    k = WIDTH / math.radians(LON1 - LON0)
    top = merc(LAT1)
    height = round((top - merc(LAT0)) * k)

    def proj(lon, lat):
        return math.radians(lon - LON0) * k, (top - merc(max(min(lat, 85), -85))) * k

    def ring(idx):
        out = []
        for i in idx:
            a = arcs[i] if i >= 0 else arcs[~i][::-1]
            out.extend(a if not out else a[1:])
        return out

    paths = []
    for g in topo["objects"]["countries"]["geometries"]:
        polys = g["arcs"] if g["type"] == "MultiPolygon" else [g["arcs"]] if g["type"] == "Polygon" else []
        d = []
        for poly in polys:
            for r in poly:
                pts = ring(r)
                if not any(LON0 - 5 <= lo <= LON1 + 5 and LAT0 - 5 <= la <= LAT1 + 8 for lo, la in pts):
                    continue
                if all(lo > LON1 or lo < LON0 - 10 for lo, _ in pts):
                    continue
                seg, last = [], None
                for lo, la in pts:
                    x, y = proj(lo, la)
                    if last and abs(x - last[0]) < MIN_STEP and abs(y - last[1]) < MIN_STEP:
                        continue
                    seg.append((x, y))
                    last = (x, y)
                if len(seg) >= 4:
                    d.append("M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in seg) + "Z")
        if d:
            paths.append([g.get("properties", {}).get("name", ""), "".join(d)])

    paths.sort()
    with open(OUT, "w") as f:
        f.write("// Copyright (c) 2026 Federico Pereira <lord.basex@gmail.com>\n")
        f.write("// Generated by scripts/relay-map.py from Natural Earth 1:50m (public domain). Do not edit.\n\n")
        f.write(f"export const MAP = {{ lon0: {LON0}, lon1: {LON1}, lat0: {LAT0}, lat1: {LAT1}, width: {WIDTH}, height: {height} }} as const;\n\n")
        f.write("/** [country, SVG path] in map units. */\n")
        f.write("export const COUNTRIES: readonly (readonly [string, string])[] = ")
        f.write(json.dumps(paths, ensure_ascii=False, separators=(",", ":")))
        f.write(";\n")
    print(f"{len(paths)} countries, {os.path.getsize(OUT)} bytes -> {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
